"""Пользовательский веб-интерфейс на базе Gradio для Enterprise Private GPT.

Предоставляет интерактивное веб-приложение, позволяющее отправлять
вопросы к локальной RAG-системе и просматривать сгенерированные ответы
вместе со ссылками на использованные фрагменты документов.
"""

import gradio as gr

from rag import ask_rag


def answer_question(question: str) -> str:
    """Обертка для вызова функции RAG-вопросно-ответной системы.

    Передает вопрос пользователя во внутренний RAG-пайплайн и возвращает ответ.
    Функция используется в качестве callback-обработчика для Gradio-интерфейса.

    Args:
        question: Строка с вопросом от пользователя.

    Returns:
        str: Ответ, сгенерированный LLM на основе найденного контекста, либо
             сообщение о том, что информация отсутствует в базе документов.
    """
    return ask_rag(question)


# Создаем веб-интерфейс с помощью компонента gr.Interface.
# Interface — это удобная абстракция Gradio, автоматически связывающая
# входные элементы (текстовое поле), логику обработки (функцию fn) и выходные элементы (текстовое поле).
demo = gr.Interface(
    fn=answer_question,
    inputs=gr.Textbox(
        label="Вопрос к базе знаний",
        placeholder="Например: Какие обстоятельства суд признал смягчающими наказание?",
        lines=3
    ),
    outputs=gr.Textbox(
        label="Ответ системы (RAG)",
        lines=15
    ),
    title="💼 Enterprise Private GPT — Локальный корпоративный ассистент",
    description=(
        "Этот веб-интерфейс позволяет взаимодействовать с защищенным локальным чат-ботом. "
        "Бот ищет информацию в базе судебных и корпоративных решений и отвечает на вопросы пользователя, "
        "строго опираясь на найденные документы. Если информации в базе нет, бот корректно сообщает об этом."
    ),
    theme="soft",  # Используем мягкую тему оформления для более профессионального вида
)

# Запускаем локальный веб-сервер Gradio.
# По умолчанию он запускается на http://127.0.0.1:7860/
if __name__ == "__main__":
    demo.launch()

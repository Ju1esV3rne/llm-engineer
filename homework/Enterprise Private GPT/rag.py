"""Модуль вопросно-ответной системы RAG (Retrieval-Augmented Generation).

Обеспечивает интеграцию векторного поиска FAISS и локальной большой языковой модели
через HTTP API (LM Studio) для генерации ответов на основе корпоративных документов.
"""

import json
from typing import Dict, Any

import faiss
import numpy as np
import requests


# --- Конфигурация RAG-системы ---
# Базовый URL локального API (LM Studio) для отправки запросов к LLM и Embeddings моделям
LM_STUDIO_URL = "http://localhost:1234/v1"

# Количество наиболее релевантных текстовых фрагментов, извлекаемых из БД
TOP_K = 3

# Пороговое значение евклидова расстояния (L2) для отсечения нерелевантных результатов.
# Подобрано экспериментально: если расстояние до ближайшего чанка больше 0.28,
# значит, вопрос пользователя не связан с базой знаний (out-of-domain).
THRESHOLD = 0.28

# Используемые локальные модели
EMBEDDING_MODEL = "text-embedding-nomic-embed-text-v1.5"
LLM_MODEL = "qwen/qwen3-8b"


# --- Загрузка и инициализация индексов ---
# Загружаем FAISS-индекс и список чанков на уровне модуля.
# Это делается один раз при импорте модуля, чтобы избежать повторного считывания файлов с диска
# при каждом запросе пользователя, что значительно снижает накладные расходы и время ответа (latency).
try:
    index = faiss.read_index("faiss.index")
except Exception as e:
    raise FileNotFoundError(
        "Файл 'faiss.index' не найден. Убедитесь, что запущен блокнот 'document_chunking.ipynb' "
        "для генерации векторного индекса."
    ) from e

try:
    with open("chunks.jsonl", "r", encoding="utf-8") as f:
        chunks = [json.loads(line) for line in f]
except Exception as e:
    raise FileNotFoundError(
        "Файл 'chunks.jsonl' не найден. Сначала выполните предобработку и чанкование документов."
    ) from e


def ask_rag(query: str) -> str:
    """Обрабатывает пользовательский запрос в рамках пайплайна RAG.

    Шаги выполнения:
    1. Генерирует семантический вектор (embedding) для входящего вопроса.
    2. Выполняет поиск ближайших соседей (Nearest Neighbors) в индексе FAISS.
    3. Сравнивает дистанцию до ближайшего совпадения с THRESHOLD для отсечения запросов вне базы.
    4. Строит контекстный промпт с найденными документами и направляет его в локальную LLM.

    Args:
        query: Входящий текстовый вопрос пользователя.

    Returns:
        str: Сгенерированный LLM ответ со ссылками на источники или сообщение о ненахождении информации.
    """
    # Шаг 1. Генерируем векторное представление пользовательского запроса.
    # Это позволяет сопоставить вопрос с чанками документов в едином семантическом пространстве.
    response = requests.post(
        f"{LM_STUDIO_URL}/embeddings",
        json={
            "model": EMBEDDING_MODEL,
            "input": query
        }
    )
    response.raise_for_status()

    # Извлекаем embedding и приводим его к типу float32, так как FAISS оптимизирован именно под этот тип.
    # Метод reshape(1, -1) преобразует одномерный массив в двумерную матрицу (1, D),
    # так как метод index.search ожидает на вход пакет запросов.
    query_embedding = np.array(
        response.json()["data"][0]["embedding"],
        dtype="float32"
    ).reshape(1, -1)

    # Шаг 2. Выполняем семантический поиск TOP_K наиболее близких чанков.
    # Метод возвращает евклидовы расстояния (distances) и индексы соответствующих элементов (indices).
    distances, indices = index.search(query_embedding, TOP_K)

    # Шаг 3. Фильтрация по порогу схожести.
    # Если расстояние до самого релевантного чанка превышает установленный порог THRESHOLD,
    # мы считаем запрос нерелевантным и отказываемся генерировать ответ на основе ложных данных,
    # предотвращая галлюцинации LLM.
    if distances[0][0] > THRESHOLD:
        return "В предоставленных документах информация не найдена."

    # Шаг 4. Конструирование контекста.
    # Извлекаем исходный текст найденных чанков по индексам из FAISS и объединяем их в единый блок.
    context_parts = []
    for i, distance in zip(indices[0], distances[0]):
        chunk = chunks[i]
        context_parts.append(
            f"Источник: {chunk['chunk_id']}\n"
            f"{chunk['text']}"
        )

    context = "\n\n---\n\n".join(context_parts)

    # Шаг 5. Формирование строгого системного промпта.
    # Даем жесткие инструкции модели опираться только на переданный контекст
    # и не использовать внешние знания или додумывать детали, что гарантирует приватность и точность.
    prompt = f"""
Перечисли все обстоятельства из контекста. Не пропускай пункты.
Не добавляй информацию, которой нет в контексте.

Контекст:
{context}

Вопрос:
{query}
"""

    # Шаг 6. Отправка запроса в локальную LLM для генерации ответа.
    # Мы используем temperature = 0.0 для минимизации вариативности генерации,
    # делая ответ максимально детерминированным и точным.
    response = requests.post(
        f"{LM_STUDIO_URL}/chat/completions",
        json={
            "model": LLM_MODEL,
            "messages": [
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            "temperature": 0
        }
    )
    response.raise_for_status()

    answer = response.json()["choices"][0]["message"]["content"]

    # Формируем список источников для прозрачности и возможности верификации ответа пользователем.
    sources = "\n".join(
        f"- Фрагмент базы знаний: {chunks[i]['chunk_id']}"
        for i in indices[0]
    )

    return f"{answer}\n\nИсточники:\n{sources}"
